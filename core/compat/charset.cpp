bool charset_to_utf8(std::string_view charset, std::string_view bytes,
                     std::string &out) {
    const auto star = charset.find('*'); // RFC 2231 language suffix
    if (star != std::string_view::npos)
        charset = charset.substr(0, star);

    if (iequals(charset, "utf-8") || iequals(charset, "utf8") ||
        iequals(charset, "us-ascii") || iequals(charset, "ascii") ||
        charset.empty()) {
        out.assign(bytes);
        return true;
    }
    if (iequals(charset, "iso-8859-1") || iequals(charset, "latin1") ||
        iequals(charset, "iso8859-1") || iequals(charset, "cp819")) {
        out = latin1_to_utf8(bytes);
        return true;
    }
    if (iequals(charset, "windows-1252") || iequals(charset, "cp1252")) {
        out = cp1252_to_utf8(bytes);
        return true;
    }
    if (iequals(charset, "macintosh") || iequals(charset, "x-mac-roman") ||
        iequals(charset, "mac") || iequals(charset, "macroman")) {
        out = macroman_to_utf8(bytes);
        return true;
    }
    if (iequals(charset, "utf-16") || iequals(charset, "utf16") ||
        iequals(charset, "utf-16be") || iequals(charset, "unicodebig")) {
        out = utf16_to_utf8(bytes, /*big_endian=*/true);
        return true;
    }
    if (iequals(charset, "utf-16le") || iequals(charset, "unicodelittle")) {
        out = utf16_to_utf8(bytes, /*big_endian=*/false);
        return true;
    }

    struct Named { const char *a, *b; const std::array<char32_t, 128> *t; };
    static const Named kTables[] = {
        {"iso-8859-2", "latin2", &kIso88592},
        {"iso-8859-5", "cyrillic", &kIso88595},
        {"iso-8859-7", "greek", &kIso88597},
        {"iso-8859-9", "latin5", &kIso88599},
        {"iso-8859-15", "latin9", &kIso885915},
        {"windows-1250", "cp1250", &kWindows1250},
        {"windows-1251", "cp1251", &kWindows1251},
        {"windows-1253", "cp1253", &kWindows1253},
        {"koi8-r", "koi8", &kKoi8R},
    };
    for (const auto &n : kTables)
        if (iequals(charset, n.a) || iequals(charset, n.b)) {
            out = decode_single_byte(bytes, *n.t);
            return true;
        }

#if defined(__APPLE__)
    if (cf_convert(charset, bytes, out))
        return true;
#endif
    return false;
}

