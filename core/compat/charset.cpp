std::string decode_single_byte(std::string_view bytes,
                               const std::array<char32_t, 128> &high) {
    std::string out;
    out.reserve(bytes.size());
    for (unsigned char c : bytes) {
        if (c < 0x80)
            out += static_cast<char>(c);
        else
            append_utf8(high[c - 0x80], out);
    }
    return out;
}

std::string latin1_to_utf8(std::string_view s) {
    std::string out;
    for (unsigned char c : s)
        append_utf8(c, out);
    return out;
}

std::string cp1252_to_utf8(std::string_view s) {
    static constexpr std::array<char32_t, 32> kHigh = {
        0x20AC, 0x0081, 0x201A, 0x0192, 0x201E, 0x2026, 0x2020, 0x2021,
        0x02C6, 0x2030, 0x0160, 0x2039, 0x0152, 0x008D, 0x017D, 0x008F,
        0x0090, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2013, 0x2014,
        0x02DC, 0x2122, 0x0161, 0x203A, 0x0153, 0x009D, 0x017E, 0x0178};
    std::string out;
    for (unsigned char c : s) {
        char32_t cp = (c >= 0x80 && c <= 0x9F) ? kHigh[c - 0x80] : c;
        append_utf8(cp, out);
    }
    return out;
}

// UTF-16 (big- or little-endian); honors a leading BOM.
std::string utf16_to_utf8(std::string_view s, bool big_endian) {
    std::string out;
    std::size_t i = 0;
    if (s.size() >= 2) {
        const unsigned char b0 = s[0], b1 = s[1];
        if (b0 == 0xFE && b1 == 0xFF) { big_endian = true; i = 2; }
        else if (b0 == 0xFF && b1 == 0xFE) { big_endian = false; i = 2; }
    }
    auto unit = [&](std::size_t k) -> char32_t {
        const unsigned char a = s[k], b = s[k + 1];
        return big_endian ? static_cast<char32_t>((a << 8) | b)
                          : static_cast<char32_t>((b << 8) | a);
    };
    for (; i + 1 < s.size(); i += 2) {
        char32_t u = unit(i);
        if (u >= 0xD800 && u <= 0xDBFF && i + 3 < s.size()) {
            const char32_t lo = unit(i + 2);
            if (lo >= 0xDC00 && lo <= 0xDFFF) {
                u = 0x10000 + ((u - 0xD800) << 10) + (lo - 0xDC00);
                i += 2;
            }
        }
        append_utf8(u, out);
    }
    return out;
}

